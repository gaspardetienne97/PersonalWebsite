const own = (instrument: PhraseInstrument, list: Omit<Phrase, "instrument">[]) =>
  list.map((p) => ({ ...p, instrument }));
export const PHRASES: Phrase[] = [
  ...own("piano", PIANO),
  ...own("guitar", GUITAR),
  ...own("ukulele", UKULELE),
  ...own("aerophone", AEROPHONE),
];

/** One instrument's phrases, easiest first. */
export const phrasesFor = (instrument: PhraseInstrument) =>
  PHRASES.filter((p) => p.instrument === instrument).sort((a, b) => a.level - b.level);

